#!/bin/sh
# Generate the Homebrew formula for a released version from its checksums.txt.
# Usage: scripts/gen-formula.sh <version-without-v> [checksums-file] > Formula/arco.rb
set -eu

ver="${1:?usage: gen-formula.sh <version e.g. 0.1.0> [checksums-file]}"
repo="mutex-solutions/arco"
base="https://github.com/$repo/releases/download/v$ver"

if [ "${2:-}" != "" ] && [ -f "$2" ]; then
  sums=$(cat "$2")
else
  sums=$(curl -fsSL "$base/checksums.txt")
fi
sha() { echo "$sums" | grep " arco_$1\$" | cut -d' ' -f1; }

d_arm=$(sha darwin_arm64.tar.gz)
d_amd=$(sha darwin_amd64.tar.gz)
l_arm=$(sha linux_arm64.tar.gz)
l_amd=$(sha linux_amd64.tar.gz)

for v in "$d_arm" "$d_amd" "$l_arm" "$l_amd"; do
  [ -n "$v" ] || { echo "missing a checksum for v$ver in checksums.txt" >&2; exit 1; }
done

cat <<EOF
# typed: false
# frozen_string_literal: true

# Homebrew formula for arco, the MCP hub for herdr fleets.
# Works on macOS and Linux (Linuxbrew). Regenerated by scripts/gen-formula.sh
# on each release; do not edit by hand.
class Arco < Formula
  desc "Stateless MCP hub for your herdr fleet"
  homepage "https://github.com/$repo"
  version "$ver"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/arco_darwin_arm64.tar.gz"
      sha256 "$d_arm"
    end
    on_intel do
      url "$base/arco_darwin_amd64.tar.gz"
      sha256 "$d_amd"
    end
  end

  on_linux do
    on_arm do
      url "$base/arco_linux_arm64.tar.gz"
      sha256 "$l_arm"
    end
    on_intel do
      url "$base/arco_linux_amd64.tar.gz"
      sha256 "$l_amd"
    end
  end

  def install
    bin.install "arco"
  end

  test do
    assert_match "arco", shell_output("#{bin}/arco version")
  end
end
EOF
